import AppKit

struct ClipItem: Identifiable, Equatable {
    enum Kind { case text, code, link, secret, file }

    let id = UUID()
    let text: String
    let kind: Kind
    let date: Date
    var fileURLs: [URL] = []
    var preview: String {
        if kind == .secret { return "••••••••••••" }
        if kind == .file, let first = fileURLs.first {
            let extra = fileURLs.count - 1
            return extra > 0 ? "\(first.lastPathComponent) and \(extra) more" : first.lastPathComponent
        }
        let line = text.split(whereSeparator: \.isNewline).first.map(String.init) ?? text
        let trimmed = line.trimmingCharacters(in: .whitespaces)
        return trimmed.count > 90 ? String(trimmed.prefix(90)) + "…" : trimmed
    }
}

/// Watches the system pasteboard. History lives in memory only and is never written to disk.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    @Published private(set) var items: [ClipItem] = []

    private let maxItems = 40
    private let secretLifetime: TimeInterval = 60
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

    private static let ignoredTypes: [NSPasteboard.PasteboardType] = [
        concealedType,
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if item.kind == .file {
            restoreFiles(item, to: pb)
        } else {
            pb.setString(item.text, forType: .string)
        }
        if item.kind == .secret {
            // Tells other clipboard managers to ignore this copy.
            pb.setData(Data(), forType: Self.concealedType)
        }
        lastChangeCount = pb.changeCount
        if item.kind == .secret {
            expire(item, clearingPasteboardAt: pb.changeCount)
        }
        if let index = items.firstIndex(of: item), index != 0 {
            items.insert(items.remove(at: index), at: 0)
        }
    }

    /// Puts the files back as plain file URLs. Finder also attaches the file name as text and an icon
    /// image, and chat apps like Discord then paste the icon instead of the file, so those are left out.
    private func restoreFiles(_ item: ClipItem, to pb: NSPasteboard) {
        let ok = pb.writeObjects(item.fileURLs as [NSURL])
        DebugLog.write("restore ok=\(ok) readBack=\(Self.fileURLs(on: pb).count) types=\((pb.types ?? []).map(\.rawValue))")
    }

    private static func fileURLs(on pb: NSPasteboard) -> [URL] {
        (pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0 == item }
    }

    func clear() {
        items.removeAll()
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        let types = pb.types ?? []
        DebugLog.write("pasteboard changed types=\(types.map(\.rawValue)) items=\(pb.pasteboardItems?.count ?? 0)")
        guard !types.contains(where: Self.ignoredTypes.contains) else { return }

        let item: ClipItem
        let files = Self.fileURLs(on: pb)
        DebugLog.write("file urls read=\(files.count)")
        if !files.isEmpty {
            item = ClipItem(text: files.map(\.path).joined(separator: "\n"), kind: .file, date: Date(), fileURLs: files)
        } else if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item = ClipItem(text: text, kind: Self.classify(text), date: Date())
        } else {
            return
        }

        items.removeAll { $0.text == item.text && $0.kind == item.kind }
        items.insert(item, at: 0)
        if items.count > maxItems { items.removeLast(items.count - maxItems) }

        if item.kind == .secret {
            expire(item, clearingPasteboardAt: pb.changeCount)
        }
    }

    /// Drops a secret from history after `secretLifetime`, and wipes the system pasteboard too
    /// if nothing else has been copied since.
    private func expire(_ item: ClipItem, clearingPasteboardAt changeCount: Int) {
        DispatchQueue.main.asyncAfter(deadline: .now() + secretLifetime) { [weak self] in
            guard let self else { return }
            self.remove(item)
            let pb = NSPasteboard.general
            if pb.changeCount == changeCount {
                pb.clearContents()
                self.lastChangeCount = pb.changeCount
            }
        }
    }

    /// Heuristic: one whitespace-free token of 8-64 characters mixing at least three of
    /// lowercase, uppercase, digits and symbols, and either containing a symbol or being 12+ long.
    /// It will sometimes flag identifiers; those are only masked, never lost.
    static func looksLikePassword(_ s: String) -> Bool {
        guard (8...64).contains(s.count), !s.contains(where: \.isWhitespace) else { return false }
        let lower = URL(string: s)?.scheme
        if let lower, ["http", "https", "file"].contains(lower) { return false }

        let hasLower = s.contains { $0.isLowercase }
        let hasUpper = s.contains { $0.isUppercase }
        let hasDigit = s.contains { $0.isNumber }
        let hasSymbol = s.contains { !$0.isLetter && !$0.isNumber }
        let classes = [hasLower, hasUpper, hasDigit, hasSymbol].filter { $0 }.count
        return classes >= 3 && (hasSymbol || s.count >= 12)
    }

    static func classify(_ text: String) -> ClipItem.Kind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)

        let secretPrefixes = ["sk-", "ghp_", "gho_", "github_pat_", "AKIA", "xoxb-", "xoxp-", "-----BEGIN"]
        if secretPrefixes.contains(where: trimmed.hasPrefix) && !trimmed.contains(" ") || trimmed.hasPrefix("-----BEGIN") {
            return .secret
        }

        if looksLikePassword(trimmed) { return .secret }

        if !trimmed.contains(where: \.isWhitespace),
           let url = URL(string: trimmed), let scheme = url.scheme, ["http", "https"].contains(scheme) {
            return .link
        }

        let codeHints = ["{", "};", "=>", "func ", "def ", "const ", "import ", "return ", "</"]
        if codeHints.contains(where: trimmed.contains) { return .code }
        return .text
    }
}
